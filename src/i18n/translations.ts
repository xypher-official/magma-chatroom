export const detectBrowserLang = (): Lang => {
  const nav = navigator.language?.slice(0, 2).toLowerCase() as Lang;
  if (["es", "en", "de", "it", "fr", "pt"].includes(nav)) return nav;
  return "en";
};

export const translate = (lang: Lang, key: string, fallback?: string): string => {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? fallback ?? key;
};